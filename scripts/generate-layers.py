#!/usr/bin/env python3
"""Generate the per-state Terraform root directories from the Git registry.

Every L2/L3 root is a few lines calling one composition module, so the directories are generated,
never hand-written (decisions #19). CI runs --check so a new region, cell or customer cannot be
merged without its state directories.

    python scripts/generate-layers.py          # write/refresh directories
    python scripts/generate-layers.py --check  # exit 1 if anything is missing or stale
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
LAYERS = ROOT / "infrastructure" / "layers"
HEADER = "# GENERATED by scripts/generate-layers.py from the Git registry. Do not edit.\n"

PROVIDERS = """terraform {
  required_version = ">= 1.7.0"
  required_providers {
    google = {
      source  = "hashicorp/google"
      version = ">= 8.0, < 9.0"
    }%(extra)s
  }

  # Partial GCS backend: bucket from backend.hcl; state prefix "%(prefix)s".
  backend "gcs" {}
}

provider "google" {}
"""

LOCAL_PROVIDER = """
    local = {
      source  = "hashicorp/local"
      version = ">= 2.5"
    }"""


def module_block(source: str, args: dict[str, str]) -> str:
    width = max(len(k) for k in args)
    body = "\n".join(f"  {k.ljust(width)} = {v}" for k, v in args.items())
    return f'module "this" {{\n  source = "{source}"\n\n{body}\n}}\n'


def root_main(depth: int, module: str, args: dict[str, str], prefix: str, local: bool = False) -> str:
    up = "/".join([".."] * depth)
    args = {"repo_root": f'"${{path.module}}/{up}"', **args}
    return (HEADER + PROVIDERS % {"prefix": prefix, "extra": LOCAL_PROVIDER if local else ""} + "\n"
            + module_block(f"{up}/infrastructure/modules/{module}", args)
            + '\noutput "result" {\n  value = module.this\n}\n')


def desired() -> dict[Path, str]:
    regions = yaml.safe_load((ROOT / "inventory/regions.yaml").read_text())["regions"]
    active = [r["name"] for r in regions if r["status"] == "active"]
    customers = sorted(
        d.name for d in (ROOT / "customers").iterdir()
        if d.is_dir() and not d.name.startswith("_") and (d / "customer.yaml").exists()
    )
    files: dict[Path, str] = {}

    for region in active:
        for group in ("devstage", "uat", "prod"):
            d = LAYERS / "L2-region" / region / group
            files[d / "main.tf"] = root_main(5, "region-footprint",
                                             {"region": f'"{region}"', "group": f'"{group}"'},
                                             f"L2/{region}/{group}", local=True)

    for group in ("uat", "prod"):
        files[LAYERS / "L2-edge" / group / "main.tf"] = root_main(4, "edge", {"group": f'"{group}"'}, f"L2-edge/{group}")
    for region in active:
        files[LAYERS / "L2-edge" / f"devstage-{region}" / "main.tf"] = root_main(
            4, "edge", {"group": '"devstage"', "region": f'"{region}"'}, f"L2-edge/devstage-{region}")

    for c in customers:
        base = LAYERS / "L3-customer" / c
        for env in ("dev", "stage", "uat", "prod"):
            files[base / env / "main.tf"] = root_main(5, "customer-infrastructure",
                                                      {"customer": f'"{c}"', "environment": f'"{env}"'}, f"L3/{c}/{env}")
        for side in ("nonprod", "prod"):
            files[base / f"keys-{side}" / "main.tf"] = root_main(5, "customer-keys",
                                                                 {"customer": f'"{c}"', "side": f'"{side}"'}, f"L3/{c}/keys-{side}")
        files[base / "exchange" / "main.tf"] = root_main(5, "data-sharing", {"customer": f'"{c}"'}, f"L3/{c}/exchange")
    return files


def generated_dirs() -> set[Path]:
    out = set()
    for layer in ("L2-region", "L2-edge", "L3-customer"):
        for main in (LAYERS / layer).rglob("main.tf"):
            if ".terraform" not in main.parts and main.read_text(encoding="utf-8").startswith(HEADER):
                out.add(main)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    want = desired()
    stale = generated_dirs() - set(want)
    problems = 0
    for path, content in sorted(want.items()):
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            problems += 1
            if args.check:
                print(f"out of date: {path.relative_to(ROOT)}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
                print(f"wrote {path.relative_to(ROOT)}")
    for path in sorted(stale):
        problems += 1
        print(f"{'stale' if args.check else 'remove by hand (state must be destroyed first)'}: {path.parent.relative_to(ROOT)}")
    if args.check:
        print("layers up to date" if problems == 0 else f"{problems} problem(s): run scripts/generate-layers.py")
        return 1 if problems else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
