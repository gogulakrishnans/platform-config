#!/usr/bin/env python3
"""Render the GitOps index that the ArgoCD ApplicationSets read (architecture §14, clarification C18).

ApplicationSet generators cannot join files. A tenant or product Application needs data from the
customer (placement, options), the catalog (runtime, sizing, routing, egress), the customer's
product selection (version pin, overrides, config) and the cell inventory (cluster region, DR state,
SQL write endpoint). This script joins them and writes one flat file per Application:

    argocd/generated/<group>/root.yaml                                values for the app-of-apps chart
    argocd/generated/<group>/tenants/<customer>-<env>[-dr].yaml       one per tenant Application
    argocd/generated/<group>/products/<customer>-<product>-<env>[-dr].yaml

Each per-Application file is also the last Helm values layer of that Application. The `argocd:`
block holds the ApplicationSet parameters (the charts ignore it); everything else is
platform-injected values that product and customer values files cannot override.

Like the placement job, it reads only Git, so it runs offline. The PR pipeline runs it after
placement and fails if the committed index is stale (`--check`).

Usage:
    python scripts/render-gitops.py            # write argocd/generated/
    python scripts/render-gitops.py --check    # exit 1 if argocd/generated/ is out of date

Exit codes: 0 ok · 1 stale (--check) · 2 validation error
"""
from __future__ import annotations

import argparse
import importlib.util
import ipaddress
import math
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = Path("argocd") / "generated"
HEADER = "# GENERATED by scripts/render-gitops.py from the Git registry. Do not edit.\n"

ENVS_BY_GROUP = {"devstage": ("dev", "stage"), "uat": ("uat",), "prod": ("prod",)}
GROUP_OF_ENV = {e: g for g, envs in ENVS_BY_GROUP.items() for e in envs}

# Per-pod overhead added to quotas: Istio sidecar and the Cloud SQL Auth Proxy (native sidecars).
SIDECAR = {"cpu_m": 100, "mem_mi": 128}
SQL_PROXY = {"cpu_m": 50, "mem_mi": 64}
SURGE = 1.25          # RollingUpdate / canary maxSurge 25%
JOB_PODS = 4          # migration hook Jobs and their retries
VERSION = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?$")


class RenderError(Exception):
    """The registry is inconsistent (exit 2)."""


def _load_repo(root: Path):
    spec = importlib.util.spec_from_file_location("placement", root / "scripts" / "placement" / "placement.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["placement"] = mod  # dataclasses resolve annotations through sys.modules
    assert spec.loader
    spec.loader.exec_module(mod)
    return mod.Repo.load(root)


# ---------------------------------------------------------------------------------------- helpers

def cpu_m(v: str | int | float) -> int:
    s = str(v)
    return int(s[:-1]) if s.endswith("m") else int(float(s) * 1000)


def mem_mi(v: str) -> int:
    units = {"Mi": 1, "Gi": 1024, "M": 1, "G": 1000}
    for u, f in units.items():
        if v.endswith(u):
            return int(float(v[: -len(u)]) * f)
    raise RenderError(f"unsupported memory quantity {v!r}")


def deep_merge(base: dict, over: dict) -> dict:
    out = dict(base)
    for k, v in (over or {}).items():
        out[k] = deep_merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def psa_cidr(region: dict, side: str) -> str:
    """Private services access range of a region (architecture §3: cidrsubnet(cidr, 2, 1))."""
    net = ipaddress.ip_network(region["cidr"][side])
    return str(list(net.subnets(prefixlen_diff=2))[1])


def gateway_host(customer: str, host: str) -> str:
    """Platform hosts collapse to the zone wildcard; custom domains stay as they are."""
    return "*." + host.split(".", 1)[1] if host.startswith(f"{customer}.") else host


def check_version(customer: str, product: str, env: str, version: str, catalog: dict, variants: bool) -> None:
    m = VERSION.match(version or "")
    if not m:
        raise RenderError(f"{customer}/{product}/{env}: version {version!r} is not semver")
    minor = f"{m.group(1)}.{m.group(2)}"
    supported = [str(s) for s in catalog["spec"]["releases"]["supported"]]
    if minor not in supported:
        raise RenderError(f"{customer}/{product}/{env}: {version} is outside the support window {supported}")
    pre = m.group(4) or ""
    if pre.startswith(f"{customer}."):
        if not variants:
            raise RenderError(f"{customer}/{product}/{env}: variant image {version} but variantImages is off")
    elif pre and env == "prod":
        raise RenderError(f"{customer}/{product}/prod: pre-release {version} is not allowed in prod")


# ---------------------------------------------------------------------------------------- render

class Renderer:
    def __init__(self, repo, root: Path = ROOT):
        self.repo = repo
        self.root = root
        self.plat = repo.platform
        self.files: dict[Path, dict] = {}
        self.root_values: dict[str, dict] = {
            g: {
                "group": g,
                "computeProject": repo.platform["projects"][repo.platform["groups"][g]["computeProject"]]["id"],
                "repoURL": "https://github.com/{org}/{repo}.git".format(**repo.platform["github"]),
                "clusters": [],
                "customers": [],
                "gatewayHosts": set(),
                "egressHosts": set(),
            }
            for g in ENVS_BY_GROUP
        }

    # ---- naming
    def project_id(self, key: str) -> str:
        return self.plat["projects"][key]["id"]

    def gcfg(self, group: str) -> dict:
        return self.plat["groups"][group]

    def registry(self, group: str) -> str:
        side = self.gcfg(group)["side"]
        hub = self.plat["hubRegion"]
        location = self.repo.regions[hub]["multiRegion"] if side == "prod" else hub
        return f"{location}-docker.pkg.dev/{self.project_id(self.gcfg(group)['platformProject'])}/products"

    def digest(self, catalog: dict, env: str, version: str) -> dict:
        """Prod deploys by the promoted digest (Binary Authorization); non-prod by tag."""
        if env != "prod":
            return {}
        rel = self.root / "products" / catalog["metadata"]["name"] / "releases.yaml"
        promoted = (yaml.safe_load(rel.read_text(encoding="utf-8")) or {}).get("promoted", {}) if rel.exists() else {}
        if not re.fullmatch(r"sha256:[a-f0-9]{64}", str(promoted.get(version, ""))):
            raise RenderError(f"{catalog['metadata']['name']} {version} has not been promoted to prod (releases.yaml)")
        return {"digest": promoted[version]}

    def hosts(self, customer: str, env: str, spec: dict) -> list[str]:
        dns = self.plat["dns"]
        if env == "prod":
            hosts = [f"{customer}.{dns['publicZone']}"]
            custom = (spec.get("options", {}).get("edge") or {}).get("customDomain")
            return hosts + ([custom] if custom else [])
        if env == "uat":
            return [f"{customer}.{dns['uatZone']}"]
        return [f"{customer}.{env}.{dns['privateZone']}"]

    # ---- clusters
    def targets(self, customer: str, group: str, placement: dict) -> list[dict]:
        cl_name = placement["cluster"]
        cl = self.repo.clusters.get(cl_name)
        if not cl:
            raise RenderError(f"{customer}: placed on {cl_name}, which is not in inventory/clusters")
        out = [{"role": "primary", "cluster": cl_name, "region": cl["region"], "drActive": bool(cl.get("drActive"))}]
        if group == "prod":
            dr = cl.get("drCluster") or {}
            if dr.get("name") != placement.get("drCluster"):
                raise RenderError(f"{customer}: drCluster {placement.get('drCluster')} does not match {cl_name}'s DR cluster")
            out.append({"role": "dr", "cluster": dr["name"], "region": dr["region"], "drActive": bool(cl.get("drActive"))})
        return out

    def add_clusters(self) -> None:
        for name, cl in sorted(self.repo.clusters.items()):
            if cl.get("status", "active") != "active":
                continue
            g = cl["group"]
            self.root_values[g]["clusters"].append(
                {"name": name, "server": f"https://{cl['endpoint']}", "region": cl["region"], "regionRole": "primary"}
            )
            if cl.get("drCluster"):
                dr = cl["drCluster"]
                self.root_values[g]["clusters"].append(
                    {"name": dr["name"], "server": f"https://{dr['endpoint']}", "region": dr["region"], "regionRole": "dr"}
                )

    # ---- per customer
    def customer(self, name: str) -> None:
        cust = self.repo.customers[name]
        spec = cust["spec"]
        if spec.get("options", {}).get("isolation", "shared") == "dedicated":
            return  # dedicated customers get their own cluster and ArgoCD destinations (separate pipeline)
        placement = spec.get("placement") or {}
        selected = self.repo.customer_products.get(name, {})
        options = spec.get("options", {})
        region = self.repo.regions[spec["region"]["primary"]]
        pair = self.repo.regions[region["drPair"]]

        for group, envs in ENVS_BY_GROUP.items():
            if group not in placement:
                raise RenderError(f"{name}: no {group} placement; run the placement job first")
            gcfg = self.gcfg(group)
            side = gcfg["side"]
            compute = self.project_id(gcfg["computeProject"])
            security = self.project_id(gcfg["securityProject"])
            sql = self.repo.sql.get(placement[group]["sqlInstance"])
            if not sql:
                raise RenderError(f"{name}: SQL instance {placement[group]['sqlInstance']} is not in inventory/sql")
            sql_cidrs = [psa_cidr(region, side)] + ([psa_cidr(pair, side)] if group == "prod" else [])
            targets = self.targets(name, group, placement[group])
            destinations = []

            for env in envs:
                ns = f"{name}-{env}"
                gsa = f"{name}-{env}@{compute}.iam.gserviceaccount.com"
                gke = {}
                for pname, sel in sorted(selected.items()):
                    catalog = self.repo.products.get(pname)
                    if not catalog:
                        raise RenderError(f"{name}: product {pname} is not in the catalog")
                    version = (sel.get("versions") or {}).get(env)
                    check_version(name, pname, env, version, catalog, bool(options.get("variantImages")))
                    if catalog["spec"]["runtime"]["type"] == "gke" and not sel.get("decommission"):
                        gke[pname] = (catalog, sel, version)

                for t in targets:
                    suffix = "-dr" if t["role"] == "dr" else ""
                    destinations.append({"cluster": t["cluster"], "namespace": ns})
                    key = f"{security}/locations/{t['region']}/keyRings/kr-{name}-{group}/cryptoKeys/{env}-data"
                    products = {
                        p: self.product_values(name, spec, env, group, t, ns, gsa, sql, c, s, v)
                        for p, (c, s, v) in gke.items()
                    }
                    self.files[OUT / group / "tenants" / f"{ns}{suffix}.yaml"] = {
                        "argocd": {
                            "name": f"tenant-{ns}{suffix}",
                            "customer": name,
                            "environment": env,
                            "group": group,
                            "cluster": t["cluster"],
                            "namespace": ns,
                            "regionRole": t["role"],
                        },
                        "customer": name,
                        "environment": env,
                        "envGroup": group,
                        "regionRole": t["role"],
                        "serviceAccounts": [
                            {"name": c["spec"]["shortCode"], "gsa": gsa} for c, _, _ in gke.values()
                        ],
                        "storage": {
                            "kmsKey": f"projects/{key}",
                            "reclaimPolicy": "Retain" if env == "prod" else "Delete",
                        },
                        "quota": self.quota(products),
                        "network": {"sqlCidrs": sql_cidrs},
                    }
                    for p, vals in products.items():
                        self.files[OUT / group / "products" / f"{name}-{p}-{env}{suffix}.yaml"] = vals
                        self.root_values[group]["egressHosts"].update(vals["egress"]["allow"])
                        self.root_values[group]["gatewayHosts"].update(
                            gateway_host(name, h) for h in vals["ingress"]["hosts"]
                        )

            self.root_values[group]["customers"].append({"name": name, "destinations": destinations})

    def product_values(self, customer, spec, env, group, target, ns, gsa, sql, catalog, sel, version) -> dict:
        c = catalog["spec"]
        short = c["shortCode"]
        sizing = deep_merge(c["sizing"][env], (sel.get("overrides") or {}).get(env, {}))
        replicas = dict(sizing["replicas"])
        hot = spec.get("options", {}).get("dr") == "hot-standby"
        if target["role"] == "dr" and not (hot or target["drActive"]):
            replicas["min"] = 1  # warm standby: minimum replicas until the cell fails over (decisions #25)
        data = c.get("data", {})
        prefix = self.plat["bucketPrefix"]
        env_vars = {}
        if data.get("storage", {}).get("required"):
            env_vars["GCS_BUCKET"] = f"{prefix}-{customer}-{short}-{env}"
        if data.get("bigQuery", {}).get("required"):
            env_vars["BQ_DATASET"] = f"{customer}_{short}_{env}".replace("-", "_")
        for t in (data.get("pubsub") or {}).get("publish", []):
            env_vars[f"PUBSUB_TOPIC_{t.upper().replace('-', '_')}"] = f"{customer}-{short}-{env}-{t}"
        env_vars["DATA_PROJECT"] = self.project_id(self.gcfg(group)["dataProject"])

        paths = sorted({p[:-2] if p.endswith("/*") else p for p in c.get("routing", {}).get("paths", [])})
        pv = c.get("persistentVolume") or {}
        compute = self.project_id(self.gcfg(group)["computeProject"])
        return {
            "argocd": {
                "name": f"{customer}-{catalog['metadata']['name']}-{env}" + ("-dr" if target["role"] == "dr" else ""),
                "customer": customer,
                "product": catalog["metadata"]["name"],
                "environment": env,
                "group": group,
                "cluster": target["cluster"],
                "namespace": ns,
                "project": customer,
                "regionRole": target["role"],
            },
            "customer": customer,
            "environment": env,
            "envGroup": group,
            "regionRole": target["role"],
            "product": {"name": catalog["metadata"]["name"], "shortCode": short},
            "image": {"registry": self.registry(group), "tag": version} | self.digest(catalog, env, version),
            "port": c["runtime"]["port"],
            "replicas": replicas,
            "resources": {"cpu": str(sizing["cpu"]), "memory": sizing["memory"]},
            "database": {
                "enabled": bool(data.get("cloudSql", {}).get("required")),
                "name": f"{customer}_{env}".replace("-", "_"),
                "schema": short.replace("-", "_"),
                "user": f"{customer}-{env}@{compute}.iam",
                "impersonate": gsa,
                # Prod: write endpoint (DNS follows promotion). Non-prod has no replica: connection name.
                "endpoint": sql.get("writeEndpoint") or f"{self.project_id(sql['project'])}:{sql['region']}:{sql['name']}",
            },
            "platformEnv": env_vars,
            "config": sel.get("config") or {},
            "ingress": {"hosts": self.hosts(customer, env, spec), "paths": paths},
            "egress": {"allow": list(c.get("egress", {}).get("allow", []))},
            "persistence": {
                "enabled": bool(pv.get("required")),
                "size": pv.get("size", "10Gi"),
                "storageClass": f"sc-{ns}",
            },
            "migration": {"enabled": target["role"] == "primary"},
        }

    @staticmethod
    def quota(products: dict) -> dict:
        cpu = mem = pods = pvcs = storage = 0
        for v in products.values():
            n = math.ceil(v["replicas"]["max"] * SURGE)
            per_cpu = cpu_m(v["resources"]["cpu"]) + SIDECAR["cpu_m"] + (SQL_PROXY["cpu_m"] if v["database"]["enabled"] else 0)
            per_mem = mem_mi(v["resources"]["memory"]) + SIDECAR["mem_mi"] + (SQL_PROXY["mem_mi"] if v["database"]["enabled"] else 0)
            cpu += n * per_cpu
            mem += n * per_mem
            pods += n
            if v["persistence"]["enabled"]:
                pvcs += v["replicas"]["max"]
                storage += v["replicas"]["max"] * mem_mi(v["persistence"]["size"])
        # Room for migration hook Jobs: the largest product's footprint, JOB_PODS times.
        jcpu = max((cpu_m(v["resources"]["cpu"]) for v in products.values()), default=0)
        jmem = max((mem_mi(v["resources"]["memory"]) for v in products.values()), default=0)
        cpu += JOB_PODS * (jcpu + SIDECAR["cpu_m"] + SQL_PROXY["cpu_m"]) if products else 0
        mem += JOB_PODS * (jmem + SIDECAR["mem_mi"] + SQL_PROXY["mem_mi"]) if products else 0
        pods += JOB_PODS if products else 0
        return {
            "requestsCpu": f"{max(cpu, 100)}m",
            "requestsMemory": f"{max(mem, 128)}Mi",
            "limitsMemory": f"{max(mem, 128)}Mi",
            "pods": max(pods, 1),
            "persistentVolumeClaims": pvcs,
            "requestsStorage": f"{storage}Mi",
        }

    def check_product_layers(self, root: Path) -> None:
        for path, vals in self.files.items():
            if "products" in path.parts:
                p = vals["argocd"]["product"]
                if not (root / "products" / p / "helm" / "values.yaml").exists():
                    raise RenderError(f"products/{p}/helm/values.yaml is missing (product values layer)")

    def render(self, root: Path) -> dict[Path, str]:
        self.add_clusters()
        for name in sorted(self.repo.customers):
            self.customer(name)
        self.check_product_layers(root)
        out = {}
        for g, vals in self.root_values.items():
            vals = vals | {"gatewayHosts": sorted(vals["gatewayHosts"]), "egressHosts": sorted(vals["egressHosts"])}
            out[OUT / g / "root.yaml"] = HEADER + yaml.safe_dump(vals, sort_keys=False)
        for path, vals in sorted(self.files.items()):
            out[path] = HEADER + yaml.safe_dump(vals, sort_keys=False)
        return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", type=Path, default=ROOT)
    ap.add_argument("--check", action="store_true", help="fail if argocd/generated/ is out of date")
    args = ap.parse_args(argv)
    root = args.repo.resolve()
    try:
        rendered = Renderer(_load_repo(root), root).render(root)
    except (RenderError, KeyError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    existing = {p.relative_to(root) for p in (root / OUT).rglob("*.yaml")} if (root / OUT).exists() else set()
    stale = sorted(existing - set(rendered))
    changed = sorted(p for p, text in rendered.items() if not (root / p).exists() or (root / p).read_text(encoding="utf-8") != text)
    if args.check:
        for p in changed:
            print(f"stale: {p.as_posix()}")
        for p in stale:
            print(f"orphan: {p.as_posix()}")
        return 1 if changed or stale else 0
    for p in stale:
        (root / p).unlink()
    for p in changed:
        (root / p).parent.mkdir(parents=True, exist_ok=True)
        (root / p).write_text(rendered[p], encoding="utf-8", newline="\n")
    print(f"{len(rendered)} files, {len(changed)} written, {len(stale)} removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
