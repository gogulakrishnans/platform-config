#!/usr/bin/env python3
"""Generate docs/catalog.md from the registry: requirement matrix, dependency graph, version matrix.

The version matrix (customer x product x environment -> pinned version) is also emitted as JSON for
the CI build artifact (architecture §7).

Usage:
    python scripts/catalog-report.py                       # write docs/catalog.md
    python scripts/catalog-report.py --check               # exit 1 if docs/catalog.md is stale
    python scripts/catalog-report.py --json matrix.json    # also write the version matrix as JSON
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = Path("docs") / "catalog.md"
ENVS = ("dev", "stage", "uat", "prod")
RUNTIME = {"gke": "GKE", "cloud-run": "Cloud Run", "mig": "MIG"}


def read(p: Path) -> dict:
    return yaml.safe_load(p.read_text(encoding="utf-8")) or {}


def load(root: Path):
    products = {d.name: read(d / "product.yaml")["spec"] for d in sorted((root / "products").iterdir())
                if d.is_dir() and not d.name.startswith("_") and (d / "product.yaml").exists()}
    customers = {d.name: read(d / "products.yaml")["spec"]["products"] for d in sorted((root / "customers").iterdir())
                 if d.is_dir() and not d.name.startswith("_") and (d / "products.yaml").exists()}
    return products, customers


def yes(b: bool) -> str:
    return "✓" if b else "–"


def version_matrix(customers: dict) -> list[dict]:
    return [
        {"customer": c, "product": p, **{e: sel["versions"].get(e) for e in ENVS}, "decommission": bool(sel.get("decommission"))}
        for c, sel_all in customers.items() for p, sel in sorted(sel_all.items())
    ]


def render(products: dict, customers: dict) -> str:
    L = ["<!-- GENERATED by scripts/catalog-report.py from products/ and customers/. Do not edit. -->",
         "# Product catalog", "",
         "The catalog is platform-owned (`products/<product>/product.yaml`, schema in "
         "[`products/_schema`](../products/_schema/product.schema.json)). Customers select products in "
         "`customers/<customer>/products.yaml`. `scripts/validate-registry.py` enforces the composition rules "
         "(architecture §6).", "",
         "## Requirement matrix", "",
         "| Product | Short code | Owner | Runtime | Cloud SQL schema | GCS bucket | BigQuery dataset | Publishes | Subscribes | Persistent volume | Egress allowlist | PII / PCI | Config export | Supported releases |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for n, p in products.items():
        d, ps, pv = p["data"], p["data"]["pubsub"], p["persistentVolume"]
        L.append("| `{}` | `{}` | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} / {} | {} | {} |".format(
            n, p["shortCode"], p["owner"], RUNTIME[p["runtime"]["type"]],
            yes(d["cloudSql"]["required"]), yes(d["storage"]["required"]), yes(d["bigQuery"]["required"]),
            ", ".join(f"`{t}`" for t in ps.get("publish", [])) or "–",
            ", ".join(f"`{t}`" for t in ps.get("subscribe", [])) or "–",
            f"{pv['size']} ({pv['approvedBy']})" if pv["required"] else "–",
            ", ".join(f"`{h}`" for h in p.get("egress", {}).get("allow", [])) or "–",
            yes(p["compliance"]["pii"]), yes(p["compliance"]["pci"]), yes(p["supportsExport"]),
            ", ".join(p["releases"]["supported"])))

    L += ["", "What a customer gets per enabled product and environment: the product's schema in the customer's "
          "database, plus a bucket, a dataset and topics only where the matrix shows them (prod also gets a DR "
          "dataset). GKE products get a Helm release per environment (and on the DR cluster in prod); Cloud Run "
          "and MIG products get a service or MIG per environment (and in the DR region in prod).", "",
          "## Sizing per environment", "",
          "| Product | dev | stage | uat | prod |", "|---|---|---|---|---|"]
    for n, p in products.items():
        cells = []
        for e in ENVS:
            s = p["sizing"][e]
            if "replicas" in s:
                cells.append(f"{s['replicas']['min']}–{s['replicas']['max']} × {s['cpu']} / {s['memory']}")
            elif "minInstances" in s:
                cells.append(f"{s['minInstances']}–{s['maxInstances']} inst × {s['cpu']} / {s['memory']}")
            else:
                cells.append(f"{s['minReplicas']}–{s['maxReplicas']} × `{s['machineType']}`")
        L.append(f"| `{n}` | " + " | ".join(cells) + " |")

    L += ["", "## Dependency graph", "",
          "Solid arrows are required dependencies (must be enabled in the same environment). Dashed arrows are "
          "Pub/Sub flows from publisher to subscriber.", "", "```mermaid", "flowchart LR"]
    for n, p in products.items():
        L.append(f"    {n.replace('-', '_')}[\"{n}<br/>{RUNTIME[p['runtime']['type']]}\"]")
    publishers = {f"{p['shortCode']}-{t}": n for n, p in products.items() for t in p["data"]["pubsub"].get("publish", [])}
    for n, p in products.items():
        for dep in p["dependencies"]["required"]:
            L.append(f"    {n.replace('-', '_')} -->|requires| {dep.replace('-', '_')}")
        for s in p["data"]["pubsub"].get("subscribe", []):
            if s in publishers:
                L.append(f"    {publishers[s].replace('-', '_')} -.->|{s}| {n.replace('-', '_')}")
    L += ["```", "", "## Version matrix", "",
          "Pinned versions per customer, product and environment (`customers/*/products.yaml`). CI publishes "
          "the same data as `version-matrix.json`.", "",
          "| Customer | Product | dev | stage | uat | prod |", "|---|---|---|---|---|---|"]
    for row in version_matrix(customers):
        note = " (decommissioning)" if row["decommission"] else ""
        L.append(f"| `{row['customer']}` | `{row['product']}`{note} | " + " | ".join(f"`{row[e]}`" for e in ENVS) + " |")

    L += ["", "## Adoption", "", "| Product | Customers |", "|---|---|"]
    for n in products:
        users = sorted(c for c, sel in customers.items() if n in sel)
        L.append(f"| `{n}` | {', '.join(f'`{u}`' for u in users) or '–'} |")
    L.append("")
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", type=Path, default=ROOT)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--json", type=Path, help="write the version matrix as JSON")
    args = ap.parse_args(argv)
    root = args.repo.resolve()
    products, customers = load(root)
    text = render(products, customers)
    if args.json:
        args.json.write_text(json.dumps(version_matrix(customers), indent=2) + "\n", encoding="utf-8")
    target = root / OUT
    current = target.read_text(encoding="utf-8") if target.exists() else None
    if args.check:
        if current != text:
            print(f"stale: {OUT.as_posix()} (run scripts/catalog-report.py)")
            return 1
        return 0
    if current != text:
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
